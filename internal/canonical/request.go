// Package canonical builds the public request template consumed by the
// selective MPC request-encryption protocol.
package canonical

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"io"
	"strconv"
	"strings"

	"tokenhive.local/half-mpc-tls/internal/protocol"
)

const (
	// AdapterOpenAIChatCompletionsV1 is the first fixed upstream request shape.
	AdapterOpenAIChatCompletionsV1 = "openai_chat_completions_v1"
	// SecretKindBearerCredential identifies the Provider-owned bytes in the template.
	SecretKindBearerCredential = "bearer_credential"
	// MaxRequestLength is the largest v1 selective-MPC plaintext capacity.
	MaxRequestLength = protocol.LargeMaxRequestBytes

	maxCredentialLength = 512
	maxBodyLength       = MaxRequestLength
)

// SecretSpan identifies Provider-owned bytes in an otherwise Hub-owned request.
// Spans are generated by this package and must not be accepted from a Consumer.
type SecretSpan struct {
	Kind   string `json:"kind"`
	Offset uint32 `json:"offset"`
	Length uint32 `json:"length"`
}

// SecretLayout is the versioned private-input layout for a canonical request.
type SecretLayout struct {
	Version uint16       `json:"version"`
	Spans   []SecretSpan `json:"spans"`
}

// Request is a canonical public template. Credential bytes are represented by
// zeroes and may only be filled inside the selective MPC circuit.
type Request struct {
	Adapter string
	Model   string
	Stream  bool
	Bytes   []byte
	Hash    [sha256.Size]byte
	Layout  SecretLayout
}

// RequestPolicy is the Consumer-controlled policy extracted from a strictly
// parsed JSON body before a Provider route is selected.
type RequestPolicy struct {
	Model  string
	Stream bool
}

// ParseOpenAIChatCompletionsPolicy rejects ambiguous JSON and returns the
// model/streaming values covered by the canonical request hash.
func ParseOpenAIChatCompletionsPolicy(body json.RawMessage) (RequestPolicy, error) {
	canonicalBody, err := canonicalJSON(body)
	if err != nil {
		return RequestPolicy{}, err
	}
	if len(canonicalBody) > maxBodyLength {
		return RequestPolicy{}, fmt.Errorf("canonical JSON body exceeds %d bytes", maxBodyLength)
	}
	model, streaming, err := extractRequestPolicy(canonicalBody)
	if err != nil {
		return RequestPolicy{}, err
	}
	return RequestPolicy{Model: model, Stream: streaming}, nil
}

// BuildOpenAIChatCompletions constructs a deterministic HTTP/1.1 request.
// Consumer headers are deliberately not accepted by this API.
func BuildOpenAIChatCompletions(host string, credentialLength int, body json.RawMessage) (Request, error) {
	if !validDNSName(host) {
		return Request{}, fmt.Errorf("canonical request host is invalid")
	}
	if credentialLength < 1 || credentialLength > maxCredentialLength {
		return Request{}, fmt.Errorf("credential length must be between 1 and %d bytes", maxCredentialLength)
	}
	canonicalBody, err := canonicalJSON(body)
	if err != nil {
		return Request{}, err
	}
	if len(canonicalBody) > maxBodyLength {
		return Request{}, fmt.Errorf("canonical JSON body exceeds %d bytes", maxBodyLength)
	}
	model, streaming, err := extractRequestPolicy(canonicalBody)
	if err != nil {
		return Request{}, err
	}

	var request bytes.Buffer
	request.Grow(256 + credentialLength + len(canonicalBody))
	request.WriteString("POST /v1/chat/completions HTTP/1.1\r\nHost: ")
	request.WriteString(host)
	request.WriteString("\r\nAuthorization: Bearer ")
	credentialOffset := request.Len()
	request.Write(make([]byte, credentialLength))
	request.WriteString("\r\nContent-Type: application/json\r\nContent-Length: ")
	request.WriteString(strconv.Itoa(len(canonicalBody)))
	request.WriteString("\r\nConnection: keep-alive\r\n\r\n")
	request.Write(canonicalBody)
	if request.Len() > MaxRequestLength {
		return Request{}, fmt.Errorf("canonical request exceeds %d bytes", MaxRequestLength)
	}

	encoded := request.Bytes()
	return Request{
		Adapter: AdapterOpenAIChatCompletionsV1,
		Model:   model,
		Stream:  streaming,
		Bytes:   encoded,
		Hash:    sha256.Sum256(encoded),
		Layout: SecretLayout{
			Version: 1,
			Spans: []SecretSpan{{
				Kind:   SecretKindBearerCredential,
				Offset: uint32(credentialOffset),
				Length: uint32(credentialLength),
			}},
		},
	}, nil
}

// NormalizeOpenAIChatCompletions validates JSON before adding the usage option
// required for authenticated streaming settlement. Duplicate keys remain errors.
func NormalizeOpenAIChatCompletions(body json.RawMessage) (json.RawMessage, error) {
	encoded, err := canonicalJSON(body)
	if err != nil {
		return nil, err
	}
	var object map[string]json.RawMessage
	if err := json.Unmarshal(encoded, &object); err != nil {
		return nil, err
	}
	if raw, exists := object["stream"]; exists {
		var streaming bool
		if string(raw) == "null" || json.Unmarshal(raw, &streaming) != nil {
			return nil, fmt.Errorf("stream must be a boolean")
		}
		if streaming {
			options := make(map[string]json.RawMessage)
			if raw, exists := object["stream_options"]; exists && string(raw) != "null" {
				if err := json.Unmarshal(raw, &options); err != nil {
					return nil, fmt.Errorf("stream_options must be an object")
				}
			}
			options["include_usage"] = json.RawMessage("true")
			object["stream_options"], err = json.Marshal(options)
			if err != nil {
				return nil, err
			}
			encoded, err = json.Marshal(object)
			if err != nil {
				return nil, err
			}
		}
	}
	if _, _, err := extractRequestPolicy(encoded); err != nil {
		return nil, err
	}
	return encoded, nil
}

func extractRequestPolicy(canonicalBody []byte) (string, bool, error) {
	var object map[string]json.RawMessage
	if err := json.Unmarshal(canonicalBody, &object); err != nil {
		return "", false, fmt.Errorf("canonical JSON request policy is invalid")
	}
	rawModel, exists := object["model"]
	if !exists {
		return "", false, fmt.Errorf("canonical JSON model is required")
	}
	var model string
	if err := json.Unmarshal(rawModel, &model); err != nil || !validModelID(model) {
		return "", false, fmt.Errorf("canonical JSON model is invalid")
	}

	streaming := false
	if rawStream, exists := object["stream"]; exists {
		if err := json.Unmarshal(rawStream, &streaming); err != nil {
			return "", false, fmt.Errorf("canonical JSON stream flag is invalid")
		}
	}
	rawOptions, hasOptions := object["stream_options"]
	if !streaming {
		if hasOptions {
			return "", false, fmt.Errorf("canonical JSON stream_options requires stream=true")
		}
		return model, false, nil
	}
	if !hasOptions {
		return "", false, fmt.Errorf("canonical JSON streaming requires stream_options.include_usage=true")
	}
	var options map[string]json.RawMessage
	if err := json.Unmarshal(rawOptions, &options); err != nil || options == nil {
		return "", false, fmt.Errorf("canonical JSON stream_options is invalid")
	}
	var includeUsage bool
	rawIncludeUsage, exists := options["include_usage"]
	if !exists || json.Unmarshal(rawIncludeUsage, &includeUsage) != nil || !includeUsage {
		return "", false, fmt.Errorf("canonical JSON streaming requires stream_options.include_usage=true")
	}
	return model, true, nil
}

func validModelID(value string) bool {
	if len(value) == 0 || len(value) > 256 {
		return false
	}
	for _, character := range []byte(value) {
		if !((character >= 'a' && character <= 'z') ||
			(character >= 'A' && character <= 'Z') ||
			(character >= '0' && character <= '9') ||
			strings.ContainsRune("-._:/", rune(character))) {
			return false
		}
	}
	return true
}

func canonicalJSON(input []byte) ([]byte, error) {
	if len(input) == 0 {
		return nil, fmt.Errorf("canonical JSON body is required")
	}
	decoder := json.NewDecoder(bytes.NewReader(input))
	decoder.UseNumber()
	value, err := decodeUniqueJSONValue(decoder)
	if err != nil {
		return nil, fmt.Errorf("canonical JSON body is invalid: %w", err)
	}
	if _, ok := value.(map[string]any); !ok {
		return nil, fmt.Errorf("canonical JSON body must be an object")
	}
	if token, err := decoder.Token(); err != io.EOF {
		if err == nil {
			return nil, fmt.Errorf("canonical JSON body contains trailing token %v", token)
		}
		return nil, fmt.Errorf("canonical JSON body has trailing data: %w", err)
	}
	encoded, err := json.Marshal(value)
	if err != nil {
		return nil, fmt.Errorf("encode canonical JSON body: %w", err)
	}
	return encoded, nil
}

func decodeUniqueJSONValue(decoder *json.Decoder) (any, error) {
	token, err := decoder.Token()
	if err != nil {
		return nil, err
	}
	delimiter, isDelimiter := token.(json.Delim)
	if !isDelimiter {
		return token, nil
	}

	switch delimiter {
	case '{':
		object := make(map[string]any)
		for decoder.More() {
			keyToken, err := decoder.Token()
			if err != nil {
				return nil, err
			}
			key, ok := keyToken.(string)
			if !ok {
				return nil, fmt.Errorf("object key is not a string")
			}
			if _, exists := object[key]; exists {
				return nil, fmt.Errorf("duplicate object key %q", key)
			}
			value, err := decodeUniqueJSONValue(decoder)
			if err != nil {
				return nil, err
			}
			object[key] = value
		}
		end, err := decoder.Token()
		if err != nil || end != json.Delim('}') {
			return nil, fmt.Errorf("object is not terminated")
		}
		return object, nil
	case '[':
		array := make([]any, 0)
		for decoder.More() {
			value, err := decodeUniqueJSONValue(decoder)
			if err != nil {
				return nil, err
			}
			array = append(array, value)
		}
		end, err := decoder.Token()
		if err != nil || end != json.Delim(']') {
			return nil, fmt.Errorf("array is not terminated")
		}
		return array, nil
	default:
		return nil, fmt.Errorf("unexpected delimiter %q", delimiter)
	}
}

func validDNSName(value string) bool {
	if value == "" || len(value) > 253 || strings.ToLower(value) != value || strings.HasSuffix(value, ".") {
		return false
	}
	for _, label := range strings.Split(value, ".") {
		if label == "" || len(label) > 63 || label[0] == '-' || label[len(label)-1] == '-' {
			return false
		}
		for _, character := range []byte(label) {
			if (character < 'a' || character > 'z') && (character < '0' || character > '9') && character != '-' {
				return false
			}
		}
	}
	return true
}
